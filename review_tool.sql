-- ----------------------------------------------------------
-- 1. locations table — PLZ data for Graubünden
-- ----------------------------------------------------------
DROP TABLE IF EXISTS `locations`;
CREATE TABLE `locations` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `plz` varchar(10) NOT NULL,
  `city` varchar(100) NOT NULL,
  `state` varchar(100) DEFAULT NULL,
  `factor` decimal(3,2) DEFAULT 1.00,
  `country` varchar(5) DEFAULT 'CH',
  PRIMARY KEY (`id`),
  UNIQUE KEY `plz` (`plz`),
  KEY `idx_plz` (`plz`),
  KEY `idx_city` (`city`),
  KEY `idx_state` (`state`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ----------------------------------------------------------
-- 2. valuations table — saved real estate appraisals
-- ----------------------------------------------------------
DROP TABLE IF EXISTS `valuations`;
CREATE TABLE `valuations` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `plz` varchar(10) NOT NULL,
  `location_name` varchar(100) DEFAULT NULL,
  `country` varchar(5) DEFAULT 'CH',
  `property_type` varchar(50) NOT NULL,
  `area` decimal(10,2) NOT NULL,
  `condition` varchar(30) NOT NULL,
  `equipment` varchar(30) NOT NULL,
  `price_per_sqm` decimal(12,2) NOT NULL DEFAULT 0.00,
  `total_value` decimal(14,2) NOT NULL DEFAULT 0.00,
  `location_factor` decimal(4,3) NOT NULL DEFAULT 1.000,
  `condition_factor` decimal(4,3) NOT NULL DEFAULT 1.000,
  `equipment_factor` decimal(4,3) NOT NULL DEFAULT 1.000,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  PRIMARY KEY (`id`),
  KEY `idx_plz` (`plz`),
  KEY `idx_location` (`location_name`),
  KEY `idx_property_type` (`property_type`),
  KEY `idx_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

